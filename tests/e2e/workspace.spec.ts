test('表单拖选到遮罩不会关闭，简介参与焦点循环，正常点击遮罩仍关闭', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
  await page.reload()
  await page.getByRole('button', { name: '笔记本', exact: true }).click()
  const trigger = page.getByRole('button', { name: '新建笔记本', exact: true })
  await trigger.click()
  const form = page.getByRole('dialog', { name: '新建笔记本' })
  const name = form.getByRole('textbox', { name: '笔记本名称', exact: true })
  const description = form.getByRole('textbox', { name: '笔记本简介', exact: true })
  await name.fill('拖动选择文字不会丢掉表单')
  await description.fill('多行简介\n保留输入内容')
  await page.keyboard.press('Tab')
  await expect(form.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(name).toBeFocused()
  await page.keyboard.press('Tab')
  await page.keyboard.press('Tab')
  await expect(description).toBeFocused()
  for (const field of [name, description]) {
    const bounds = (await field.boundingBox())!
    const modal = (await form.boundingBox())!
    await page.mouse.move(bounds.x + bounds.width - 16, bounds.y + 16)
    await page.mouse.down()
    await page.mouse.move(modal.x - 24, bounds.y + 16, { steps: 10 })
    await page.mouse.up()
    await expect(form).toBeVisible()
  }
  await expect(name).toHaveValue('拖动选择文字不会丢掉表单')
  await expect(description).toHaveValue('多行简介\n保留输入内容')
  const style = await description.evaluate(el => {
    const style = getComputedStyle(el)
    return { paddingTop: parseFloat(style.paddingTop), lineHeight: parseFloat(style.lineHeight), height: el.clientHeight }
  })
  expect(style.paddingTop).toBeGreaterThanOrEqual(8)
  expect(style.height).toBeGreaterThan(style.lineHeight * 3)
  await page.mouse.click(12, 12)
  await expect(form).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await expect(page.getByRole('textbox', { name: '笔记本名称', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(form).toHaveCount(0)
})

