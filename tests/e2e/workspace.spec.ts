import { expect, test, type Page } from '@playwright/test'
import { resetServer } from './reset-server'

const headers = { Authorization: 'Bearer dev-token' }
async function sidebar(page: Page) {
  if (page.viewportSize()!.width <= 1020 && !await page.locator('.sidebar-pane').evaluate(el => el.classList.contains('is-open'))) {
    await page.getByRole('button', { name: '打开侧栏', exact: true }).click()
  }
}
async function dataSettings(page: Page) {
  await sidebar(page)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
}

