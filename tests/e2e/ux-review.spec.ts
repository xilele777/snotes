import { expect, test } from '@playwright/test'
import { resetServer } from './reset-server'

const headers = { Authorization: 'Bearer dev-token' }
test.beforeEach(() => resetServer())

for (const width of [1440, 390, 320]) {
  test(`review improvements preserve editing and support list undo at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.request.post('/api/notes', { headers, data: { id: crypto.randomUUID(), title: '审阅优化验收', summary: '继续写作', content: '# 审阅优化验收\n\n继续写作', create_time: Date.now() } })
    await page.goto('/')
    await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
    await page.reload()
    await expect(page.locator('.note-item')).toHaveCount(1)
    await page.locator('.note-select').click()
    const editor = page.locator('.ProseMirror')
    await expect(editor).toContainText('审阅优化验收')
    await expect(page.locator('.format-bar [data-op="undo"]')).toBeVisible()
    await expect(page.locator('.editor-top-bar [data-op="undo"]')).toHaveCount(0)
    await page.getByRole('button', { name: '更多操作', exact: true }).click()
    await page.locator('[data-action="home-feed"]').click()
    await expect(page.locator('.layout')).toHaveAttribute('data-view', 'all')
    await expect(page.locator('.note-item')).toHaveCount(0)
    await expect(editor).toContainText('继续写作')
    await editor.click()
    await page.keyboard.press('Control+End')
    await page.keyboard.type(' edited')
    await expect(editor).toContainText('edited')
    await page.getByRole('button', { name: '更多操作', exact: true }).click()
    await page.locator('[data-action="home-feed"]').click()
    if (width <= 720) await page.getByRole('button', { name: '返回列表', exact: true }).click()
    await expect(page.locator('.note-item')).toHaveCount(1)
    await page.locator('.note-more').click()
    await page.getByRole('menuitemcheckbox', { name: '星标', exact: true }).click()
    await expect(page.locator('.note-star')).toBeVisible()
    await page.locator('.note-more').click()
    await page.getByRole('menuitem', { name: '移入回收站', exact: true }).click()
    await expect(page.locator('.note-item')).toHaveCount(0)
    await expect(page.getByRole('alertdialog')).toHaveCount(0)
    await page.locator('.toast').getByRole('button', { name: '撤销', exact: true }).click()
    await expect(page.locator('.note-item')).toHaveCount(1)
    await page.locator('.note-select').click()
    await expect(editor).toContainText('edited')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `tmp/ux-review-${width}.png`, fullPage: true })
  })
}

test('notebook recent entry opens a note and detach preserves it as an independent note', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const noteId = crypto.randomUUID()
  const bookId = crypto.randomUUID()
  await page.request.post('/api/notes', { headers, data: { id: noteId, title: '独立笔记验收', summary: '', content: '# 独立笔记验收\n\n正文保留', create_time: Date.now() } })
  await page.request.post('/api/knowledge-bases', { headers, data: { id: bookId, operation_id: crypto.randomUUID(), name: '审阅验收本', description: '', icon: '', ord: 0, invalid: 0 } })
  await page.request.put(`/api/knowledge-bases/${bookId}/toc`, { headers, data: { nodes: [{ id: 'ux-note', kind: 'note', parent_id: null, ord: 0, title: null, note_id: noteId }], base_toc_version: 0, operation_id: crypto.randomUUID() } })
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
  await page.reload()
  await page.getByRole('button', { name: '笔记本', exact: true }).click()
  await page.locator('.kb-card-link').filter({ hasText: '审阅验收本' }).click()
  await page.getByRole('region', { name: '最近更新的笔记' }).getByRole('button').click()
  await expect(page.locator('.ProseMirror')).toContainText('正文保留')
  await page.locator('.kb-node-menu').click()
  await page.getByRole('menuitem', { name: '移出笔记本，转为独立笔记', exact: true }).click()
  await expect(page.locator('.kb-tree-row')).toHaveCount(0)
  await page.getByRole('button', { name: '全部笔记', exact: true }).click()
  await expect(page.locator('.note-select')).toContainText('独立笔记验收')
  await page.locator('.note-select').click()
  await expect(page.locator('.ProseMirror')).toContainText('正文保留')
})
