import { expect, test } from '@playwright/test'
import { resetServer } from './reset-server'

test.beforeEach(() => resetServer())

test('分栏拖动、键盘与刷新记忆；窄窗口约束后恢复原宽度', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
  await page.reload()
  const sidebar = page.getByRole('separator', { name: '调整侧栏宽度' })
  const list = page.getByRole('separator', { name: '调整笔记列表宽度' })
  await sidebar.focus()
  await page.keyboard.press('ArrowRight')
  await expect(sidebar).toHaveAttribute('aria-valuenow', '248')
  const bounds = (await list.boundingBox())!
  await page.mouse.move(bounds.x + bounds.width / 2, 400)
  await page.mouse.down()
  await page.mouse.move(bounds.x + bounds.width / 2 + 100, 400, { steps: 8 })
  await page.mouse.up()
  await expect(page.locator('html')).not.toHaveClass(/is-resizing-workspace/)
  await expect(list).toHaveAttribute('aria-valuenow', '436')
  await page.reload()
  await expect(sidebar).toHaveAttribute('aria-valuenow', '248')
  await expect(list).toHaveAttribute('aria-valuenow', '436')
  await page.setViewportSize({ width: 1024, height: 900 })
  await expect.poll(async () => (await page.locator('.editor-pane').boundingBox())!.width).toBeGreaterThanOrEqual(360)
  await expect(list).toHaveAttribute('aria-valuenow', '416')
  await page.setViewportSize({ width: 900, height: 900 })
  await expect.poll(async () => (await page.locator('.list-pane').boundingBox())!.width).toBe(436)
  await expect(page.getByRole('separator')).toHaveCount(0)
  await page.setViewportSize({ width: 721, height: 900 })
  await expect.poll(async () => (await page.locator('.editor-pane').boundingBox())!.width).toBeGreaterThanOrEqual(360)
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(list).toHaveAttribute('aria-valuenow', '436')
  await list.dblclick()
  await expect(list).toHaveAttribute('aria-valuenow', '336')
  await sidebar.focus()
  await page.keyboard.press('Home')
  await expect(sidebar).toHaveAttribute('aria-valuenow', '200')
  await page.keyboard.press('Enter')
  await expect(sidebar).toHaveAttribute('aria-valuenow', '232')
})

test('列表独立收起保留编辑器与撤销，搜索和导航重新显示列表，手机始终可返回', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
  await page.reload()
  await page.getByRole('button', { name: '新建笔记', exact: true }).click()
  const editor = page.locator('.ProseMirror')
  await expect(editor).toBeVisible()
  await editor.pressSequentially('Layout continuity')
  await editor.evaluate(el => el.setAttribute('data-continuity', 'original'))
  await page.getByRole('button', { name: '收起笔记列表', exact: true }).click()
  await expect(page.locator('.list-pane')).toBeHidden()
  await expect(editor).toHaveAttribute('data-continuity', 'original')
  await page.screenshot({ path: testInfo.outputPath('desktop-list-hidden.png') })
  await page.getByRole('button', { name: '展开笔记列表', exact: true }).click()
  await expect(page.locator('.list-pane')).toBeVisible()
  await editor.click()
  await page.keyboard.press('Control+z')
  await expect(editor).not.toContainText('Layout continuity')
  await page.getByRole('button', { name: '收起笔记列表', exact: true }).click()
  await page.keyboard.press('Control+k')
  await expect(page.getByRole('searchbox', { name: '搜索笔记', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '收起笔记列表', exact: true }).click()
  await page.getByRole('button', { name: '星标笔记', exact: true }).click()
  await expect(page.locator('.list-pane')).toBeVisible()
  await page.getByRole('button', { name: '全部笔记', exact: true }).click()
  await page.locator('.note-select').first().click()
  await page.getByRole('button', { name: '收起笔记列表', exact: true }).click()
  for (const width of [1920, 1440, 1024, 900, 721, 390, 320]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(await page.locator('.editor-top-bar').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    if (width <= 1020) await expect(page.getByRole('button', { name: '展开笔记列表', exact: true })).toBeHidden()
  }
  await page.getByRole('button', { name: '返回列表', exact: true }).click()
  await expect(page.locator('.list-pane')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('mobile-list.png') })
})
