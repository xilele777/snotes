import { expect, test, type Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { unzipSync, strFromU8 } from 'fflate'
import { resetServer } from './reset-server'

const headers = { Authorization: 'Bearer dev-token' }
test.beforeEach(() => resetServer())
async function seedNote(page: Page, title: string, content: string, extra = {}) {
  const id = crypto.randomUUID()
  expect((await page.request.post('/api/notes', { headers, data: { id, title, summary: '', content, create_time: Date.now(), ...extra } })).ok()).toBe(true)
  return id
}
async function signIn(page: Page, width = 1440) {
  await page.setViewportSize({ width, height: 844 })
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
  await page.reload()
  await expect(page.locator('.note-item').first()).toBeVisible()
}

