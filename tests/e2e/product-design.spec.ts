test('同步的空正文可以导出为完整备份', async ({ page }, testInfo) => {
  const noteId = await seedNote(page, '', '')
  await signIn(page)
  await expect(page.locator('.snotes-vditor [role=textbox]:visible')).toBeVisible()
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: '数据', exact: true }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出全部', exact: true }).click()
  const file = await download
  const path = testInfo.outputPath('empty-body-backup.zip')
  await file.saveAs(path)
  const entries = unzipSync(await readFile(path))
  const index = JSON.parse(strFromU8(entries['index.json']!))
  const record = index.notes.find((n: { id: string }) => n.id === noteId)
  expect(record).toBeTruthy()
  expect(strFromU8(entries[record.file]!)).toBe('')
  await expect(page.locator('.backup-progress')).toContainText('已导出 1 条笔记')
})

test('连续删除可逐条撤销', async ({ page }) => {
  await seedNote(page, '第一条', '# 第一条')
  await seedNote(page, '第二条', '# 第二条')
  await signIn(page)
  await expect(page.locator('.note-item')).toHaveCount(2)
  for (const title of ['第一条', '第二条']) {
    await page.locator('.note-item').filter({ hasText: title }).locator('.note-more').click()
    await page.getByRole('menuitem', { name: '移入回收站', exact: true }).click()
  }
  await expect(page.locator('.note-item')).toHaveCount(0)
  await page.locator('.toast').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.note-item')).toHaveCount(1)
  await expect(page.locator('.toast').getByRole('button', { name: '撤销', exact: true })).toBeVisible()
  await page.locator('.toast').getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.note-item')).toHaveCount(2)
})

test('长菜单可滚动到最后操作，手机常用工具不需横向查找', async ({ page }, testInfo) => {
  await seedNote(page, '手机验证', '# 手机验证')
  for (let i = 1; i <= 20; i++) await page.request.post('/api/groups', { headers, data: { group_id: crypto.randomUUID(), name: `分组${i}`, ord: i } })
  await signIn(page, 390)
  await page.locator('.note-more').first().click()
  const menu = page.getByRole('menu', { name: '笔记操作' })
  await expect(menu.getByRole('menuitemradio', { name: '分组20', exact: true })).toHaveCount(1)
  expect(await menu.evaluate(e => e.clientHeight < e.scrollHeight && e.getBoundingClientRect().bottom <= innerHeight)).toBe(true)
  await menu.getByRole('menuitemradio', { name: '分组20', exact: true }).click()
  await expect(page.locator('.note-group-label')).toHaveText('分组20')
  await page.locator('.note-select').click()
  const toolbar = page.locator('.vditor-toolbar')
  await expect(toolbar.locator('[data-type=undo]')).toBeVisible()
  await expect(toolbar.locator('[data-type=redo]')).toBeVisible()
  await expect(toolbar.locator('[data-type=check]')).toBeVisible()
  expect((await toolbar.locator('[data-type=undo]').boundingBox())!.width).toBeGreaterThanOrEqual(44)
  await expect(toolbar.locator('[data-type=bold]')).toBeHidden()
  await expect(toolbar.locator('[data-type=outdent]')).toBeHidden()
  await expect(toolbar.locator('[data-type=outline]')).toBeHidden()
  await toolbar.locator('[data-type=mobile-format]').click()
  await expect(toolbar.locator('[data-type=bold]')).toBeVisible()
  await expect(toolbar.locator('[data-type=outline]')).toBeHidden()
  await expect(toolbar.locator('[data-type=mobile-format]')).toHaveAttribute('aria-expanded', 'true')
  await toolbar.locator('[data-type=mobile-format]').click()
  await expect(toolbar.locator('[data-type=bold]')).toBeHidden()
  await expect(toolbar.locator('[data-type=mobile-format]')).toHaveAttribute('aria-expanded', 'false')
  expect(await toolbar.evaluate(e => e.scrollWidth <= e.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mobile-tools.png') })
  await page.setViewportSize({ width: 320, height: 700 })
  await toolbar.locator('[data-type=mobile-format]').click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('mobile-tools-expanded-320.png') })
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark')
  await page.screenshot({ path: testInfo.outputPath('mobile-tools-expanded-dark-320.png') })
})

test('缺正文可明确提示并重试；离线编辑显示本机保存状态', async ({ page, context }) => {
  await seedNote(page, '离线验证', '# 离线验证\n\n原正文')
  await page.route('**/api/sync/bodies', route => route.abort('failed'))
  await signIn(page, 390)
  await page.getByRole('searchbox', { name: '搜索笔记', exact: true }).fill('只在正文中搜索')
  await expect(page.locator('.search-coverage')).toContainText('1 篇正文未下载')
  await page.locator('.search-clear').click()
  await page.locator('.note-select').click()
  await expect(page.locator('.body-unavailable')).toContainText('本机尚未下载这篇正文')
  await context.setOffline(true)
  await page.getByRole('button', { name: '重新下载正文', exact: true }).click()
  await expect(page.locator('.body-unavailable')).toContainText('当前离线')
  await page.unroute('**/api/sync/bodies')
  // Reconnecting automatically downloads missing bodies; the retry button can
  // disappear before Playwright clicks it. Forced retry is covered at unit level.
  await context.setOffline(false)
  const editor = page.locator('.snotes-vditor [role=textbox]:visible')
  await expect(editor).toContainText('原正文')
  await context.setOffline(true)
  await editor.click()
  await page.keyboard.press('Control+End')
  await page.keyboard.type(' offline change')
  await expect(page.locator('.note-save-status')).toContainText('已保存到本机 · 离线')
  await context.setOffline(false)
  await expect(page.locator('.note-save-status')).toContainText('已保存并同步')
})
