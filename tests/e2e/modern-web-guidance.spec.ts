import { expect, test, type Page } from '@playwright/test'
import { resetServer } from './reset-server'

test.beforeEach(() => resetServer())
async function signIn(page: Page) {
  await page.goto('/')
  await page.evaluate(() => localStorage.setItem('snotes_token', 'dev-token'))
  await page.reload()
  await expect(page.locator('.layout')).toBeVisible()
}

test('empty and whitespace tokens reach native validation, then a valid token signs in', async ({ page }) => {
  await page.goto('/')
  const token = page.locator('#access-token')
  const submit = page.getByRole('button', { name: '进入我的便签' })
  await expect(submit).toBeEnabled()
  await submit.click()
  await expect(token).toBeFocused()
  expect(await token.evaluate((el: HTMLInputElement) => el.validity.valueMissing)).toBe(true)
  await token.fill('   ')
  await submit.click()
  expect(await token.evaluate((el: HTMLInputElement) => el.validity.patternMismatch)).toBe(true)
  await expect(token).toBeFocused()
  await token.fill('dev-token')
  await submit.click()
  await expect(page.locator('.layout')).toBeVisible()
})

test('all views share the same unique main landmark and preserve pane layout', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await signIn(page)
  const main = await page.locator('#workspace-main').elementHandle()
  for (const name of ['全部笔记', '星标笔记', '已隐藏', '回收站', '笔记本', '统计', '设置', '随手记']) {
    await page.getByRole('navigation').getByRole('button', { name, exact: true }).click()
    await expect(page.getByRole('main')).toHaveCount(1)
    expect(await main!.evaluate(el => el === document.querySelector('main'))).toBe(true)
  }
  await expect(page.getByRole('search')).toHaveCount(1)
  await page.getByRole('button', { name: '新建笔记', exact: true }).click()
  await expect(page.locator('.snotes-vditor [role=textbox]:visible')).toBeVisible()
  const bounds = await page.locator('.sidebar-pane, .list-pane, .editor-pane').evaluateAll(es => es.map(el => {
    const r = el.getBoundingClientRect()
    return { x: r.x, width: r.width, height: r.height }
  }))
  expect(bounds[0]!.x).toBe(0)
  expect(bounds[1]!.x).toBe(bounds[0]!.width)
  expect(bounds[2]!.x).toBe(bounds[1]!.x + bounds[1]!.width)
  expect(bounds.every(b => b.height === 900)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('workspace-desktop-light.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('main')).toHaveCount(1)
  await expect(page.locator('.editor-pane')).toBeVisible()
  await expect(page.locator('.list-pane')).toBeHidden()
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.screenshot({ path: testInfo.outputPath('workspace-mobile-dark.png'), animations: 'disabled' })
})

test('Tab and Shift+Tab leave both command menus and button groups naturally', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await signIn(page)
  await page.getByRole('button', { name: '新建笔记', exact: true }).click()
  await expect(page.locator('.snotes-vditor [role=textbox]:visible')).toBeVisible()
  for (const name of ['笔记排序：最近更新', '移至分组']) {
    const trigger = page.getByRole('button', { name, exact: true })
    for (const key of ['Tab', 'Shift+Tab']) {
      await trigger.focus()
      await page.keyboard.press(key)
      const expected = await page.evaluateHandle(() => document.activeElement)
      await trigger.focus()
      await trigger.click()
      await expect(page.locator('.action-menu')).toBeVisible()
      await page.keyboard.press(key)
      await expect(page.locator('.action-menu')).toHaveCount(0)
      expect(await expected.evaluate(el => el === document.activeElement)).toBe(true)
      expect(await trigger.evaluate(el => el === document.activeElement)).toBe(false)
      await expected.dispose()
    }
  }
})

test('mobile drawer contains focus, nested native dialogs close first, resizing restores sidebar semantics', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await signIn(page)
  const trigger = page.getByRole('button', { name: '打开侧栏', exact: true })
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: '导航', exact: true })
  await expect(drawer).toBeVisible()
  await expect(drawer).toHaveAttribute('aria-modal', 'true')
  await expect(page.locator('#workspace-main')).toHaveAttribute('inert', '')
  const close = drawer.getByRole('button', { name: '关闭侧栏' })
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  expect(await drawer.evaluate(el => el.contains(document.activeElement))).toBe(true)
  await drawer.getByRole('button', { name: '新建分组', exact: true }).click()
  const form = page.getByRole('dialog', { name: '新建分组', exact: true })
  await expect(form).toBeVisible()
  expect(await form.evaluate(el => el.matches(':modal'))).toBe(true)
  await page.keyboard.press('Escape')
  await expect(form).toHaveCount(0)
  await expect(drawer).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.mouse.click(380, 200)
  await expect(drawer).toHaveCount(0)
  await trigger.click()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(page.locator('.sidebar-pane')).not.toHaveAttribute('role', 'dialog')
  await expect(page.locator('.sidebar-pane')).not.toHaveAttribute('popover')
  await expect(page.locator('#workspace-main')).not.toHaveAttribute('inert')
})

test('native confirmation uses safe initial focus, restores it after closing and supports light dismiss', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await signIn(page)
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('tab', { name: '关于', exact: true }).click()
  const logout = page.locator('[data-action=logout]')
  await logout.click()
  const dialog = page.getByRole('dialog', { name: '退出登录？', exact: true })
  await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  await expect(dialog).toHaveCSS('opacity', '1')
  await page.screenshot({ path: testInfo.outputPath('native-confirmation.png'), animations: 'disabled' })
  expect(await dialog.evaluate(el => el.matches(':modal'))).toBe(true)
  await page.keyboard.press('Shift+Tab')
  // A native modal may let Tab reach browser chrome; page controls remain inert.
  await logout.evaluate(el => (el as HTMLElement).focus())
  await expect(logout).not.toBeFocused()
  await dialog.getByRole('button', { name: '取消', exact: true }).focus()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(logout).toBeFocused()
  await logout.click()
  await page.mouse.click(12, 12)
  await expect(dialog).toHaveCount(0)
  await expect(logout).toBeFocused()
})

test('image metadata survives the editor-to-lightbox path and empty alt gets a numbered fallback', async ({ page }) => {
  const response = await page.request.post('/api/notes', {
    headers: { Authorization: 'Bearer dev-token' },
    data: { id: crypto.randomUUID(), create_time: Date.now(), title: '图片说明', summary: '', content: '![作者提供的结构图说明](/snotes.svg)\n\n![](/snotes.svg)' },
  })
  expect(response.ok()).toBe(true)
  await signIn(page)
  const images = page.locator('.snotes-vditor [role=textbox]:visible img')
  await expect(images).toHaveCount(2)
  await images.first().dblclick()
  const image = page.getByRole('dialog', { name: '查看图片' }).locator('.lightbox-stage img')
  await expect(image).toHaveAttribute('alt', '作者提供的结构图说明')
  await page.getByRole('button', { name: '下一张', exact: true }).click()
  await expect(image).toHaveAttribute('alt', '图片 2 / 2')
  // Next is now disabled; keyboard navigation must still work.
  await page.keyboard.press('ArrowLeft')
  await expect(image).toHaveAttribute('alt', '作者提供的结构图说明')
})

test('dialog fallback preserves drag selection and exits before releasing native modality', async ({ page }) => {
  await page.addInitScript(() => { Reflect.deleteProperty(HTMLDialogElement.prototype, 'closedBy') })
  await signIn(page)
  await page.addStyleTag({ content: '.native-dialog, .native-dialog::backdrop { transition-property: opacity !important; transition-behavior: normal !important; }' })
  const trigger = page.getByRole('button', { name: '新建分组', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '新建分组' })
  // Disable the native light-dismiss path to exercise the pointer fallback.
  await dialog.evaluate(el => el.setAttribute('closedby', 'closerequest'))
  await expect(dialog).toHaveCSS('opacity', '1')
  const field = dialog.getByRole('textbox')
  await field.fill('保留拖选')
  const bounds = (await field.boundingBox())!
  await page.mouse.move(bounds.x + 30, bounds.y + 10)
  await page.mouse.down()
  await page.mouse.move(12, 12)
  await page.mouse.up()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '取消', exact: true }).evaluate(el => (el as HTMLButtonElement).click())
  expect(await dialog.evaluate(el => el.matches(':modal'))).toBe(true)
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await trigger.click()
  await dialog.evaluate(el => el.setAttribute('closedby', 'closerequest'))
  await page.mouse.click(12, 12)
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
